import Link from 'next/link'
import { requirePermission } from '@/lib/authz'
import { prisma } from '@/lib/db'
import { activePlans } from '@/server/pathway'
import { publishedJobs } from '@/server/jobs'
import { formatDate } from '@/lib/utils'
import { label } from '@/lib/options'
import { PathwayGeneratorForm } from '@/components/candidate/gap-pathway-forms'
import { PathwayTimeline } from '@/components/candidate/pathway-timeline'
import { DemoBadge, EmptyState, InfoNote, PageHeader, StatCard } from '@/components/common'
import { Button } from '@/components/ui/button'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { Badge } from '@/components/ui/badge'

export const metadata = { title: 'Learning pathways' }

/** Which engine ordered a stored plan, using the value the server wrote with it. */
function pathwayEngine(generatedBy: string) {
  if (generatedBy === 'PATHWAY_PLANNER_RULES') return 'ordered by the rule planner'
  if (generatedBy.endsWith(':DETERMINISTIC')) return 'the agent could not run, so the rule planner ordered it'
  if (generatedBy.endsWith(':AI')) return 'ordered by the pathway agent'
  return `generated by ${generatedBy}`
}

export default async function CandidatePathwaysPage() {
  const principal = await requirePermission('candidate.plan.read')

  if (!principal.candidateProfileId) {
    return (
      <div className="space-y-6">
        <PageHeader eyebrow="Pathways" title="Learning pathways" description="No candidate profile is attached to this account yet." />
        <EmptyState
          title="Onboarding comes first"
          description="A pathway is built from the gap between your skills and a role’s requirements."
          action={
            <Button className="bg-brand-600 hover:bg-brand-700" nativeButton={false} render={<Link href="/candidate/onboarding" />}>
              Start onboarding
            </Button>
          }
        />
      </div>
    )
  }

  const [plans, jobs, skillCount] = await Promise.all([
    activePlans(principal),
    publishedJobs({ take: 60 }),
    prisma.candidateSkill.count({ where: { candidateProfileId: principal.candidateProfileId } }),
  ])

  const options = [
    { value: 'AUTO', label: 'Automatic — my closest matched roles' },
  ].concat(jobs.map((job) => ({ value: job.id, label: `${job.title} — ${job.organization.name}` })))

  const openItems = plans
    .filter((plan) => plan.status === 'ACTIVE')
    .reduce((total, plan) => total + plan.items.filter((item) => item.status !== 'COMPLETED').length, 0)
  const completedItems = plans.reduce(
    (total, plan) => total + plan.items.filter((item) => item.status === 'COMPLETED').length,
    0,
  )

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Pathways"
        title="Learning pathways"
        description="Ordered steps taken from the curated catalogue, each one there because it addresses a gap the report found. Where the catalogue has nothing for a gap, the plan says so rather than inventing a course."
        actions={
          <>
            <Button variant="outline" nativeButton={false} render={<Link href="/candidate/gap-report" />}>
              Skill gaps
            </Button>
            <Button variant="ghost" nativeButton={false} render={<Link href="/candidate/skills" />}>
              Skills inventory
            </Button>
          </>
        }
      />

      <div className="grid gap-3 sm:grid-cols-3">
        <StatCard label="Plans on file" value={plans.length} hint={`${plans.filter((plan) => plan.status === 'ACTIVE').length} active`} />
        <StatCard label="Steps to work through" value={openItems} hint={`${completedItems} completed`} tone={openItems > 0 ? 'warning' : 'positive'} />
        <StatCard label="Skills on your inventory" value={skillCount} hint="Each completed step can attach evidence here." tone="neutral" />
      </div>

      {plans.length === 0 ? (
        <div className="space-y-4">
          <EmptyState
            title="No pathway built yet"
            image="learning-next-step"
            description="Pick a target role — or leave it automatic — and the planner runs a fresh gap analysis, then orders catalogue resources by severity. Nothing appears unless it maps to a gap."
          />
          <InfoNote tone="warning" title="An empty catalogue produces an honest refusal">
            If no stored resource covers a gap, the build stops and names the gaps it could not fill. That is the
            intended behaviour: an invented course link would be worse than no link.
          </InfoNote>
        </div>
      ) : null}

      <div className="grid gap-4 lg:grid-cols-[minmax(0,1fr)_22rem] lg:items-start">
        <div className="flex flex-col gap-4">
          {plans.map((plan) => {
            return (
              <Card key={plan.id} className={plan.status === 'ABANDONED' ? 'opacity-75' : undefined}>
                <CardHeader className="pb-3">
                  <div className="flex flex-wrap items-start justify-between gap-2">
                    <div className="min-w-0">
                      <CardTitle className="text-base">{plan.title}</CardTitle>
                      <CardDescription className="mt-1 text-xs">{plan.goal}</CardDescription>
                    </div>
                    <div className="flex flex-wrap items-center gap-2">
                      <Badge variant={plan.status === 'ACTIVE' ? 'default' : 'secondary'}>
                        {label(plan.status).toLowerCase()}
                      </Badge>
                      {plan.items.some((item) => item.resource.demonstration) ? <DemoBadge /> : null}
                    </div>
                  </div>
                  <p className="pt-1 text-sm leading-relaxed text-muted-foreground">{plan.summary}</p>
                  <p className="pt-1 text-xs leading-snug text-muted-foreground">
                    Built {formatDate(plan.createdAt)} · {plan.items.length} step{plan.items.length === 1 ? '' : 's'} ·{' '}
                    {pathwayEngine(plan.generatedBy)}
                  </p>
                </CardHeader>
                <CardContent className="flex flex-col gap-3">
                  {plan.items.length === 0 ? (
                    <p className="text-sm text-muted-foreground">This plan has no steps — the catalogue covered nothing.</p>
                  ) : (
                    <PathwayTimeline
                      planId={plan.id}
                      active={plan.status === 'ACTIVE'}
                      steps={plan.items.map((item) => ({
                        id: item.id,
                        position: item.position,
                        status: item.status,
                        completedAt: item.completedAt,
                        note: item.note,
                        gapSkillName: item.resource.skill?.name ?? null,
                        resource: {
                          title: item.resource.title,
                          provider: item.resource.provider,
                          type: item.resource.type,
                          url: item.resource.url,
                          durationHours: item.resource.durationHours,
                          isFree: item.resource.isFree,
                          costLabel: item.resource.costLabel,
                          outcome: item.resource.outcome,
                          demonstration: item.resource.demonstration,
                        },
                      }))}
                    />
                  )}

                  {plan.targetJobId ? (
                    <Button variant="outline" size="sm" nativeButton={false} render={<Link href={`/candidate/jobs/${plan.targetJobId as string}`} />}>
                      The role this pathway targets
                    </Button>
                  ) : null}
                </CardContent>
              </Card>
            )
          })}
        </div>

        <PathwayGeneratorForm options={options} />
      </div>

      <InfoNote tone="privacy" title="Progress you record, not progress observed">
        Marking a step complete writes your own status and can attach evidence to the matching skill. The platform does
        not watch the external course, cannot confirm you finished it, and does not mark a skill assessed because of a
        tick here. Reassessment happens through the practice assessments screen.
      </InfoNote>

      <div className="flex flex-wrap gap-2">
        <Button variant="outline" nativeButton={false} render={<Link href="/candidate/assessments" />}>
          Reassess a skill
        </Button>
        <Button variant="ghost" nativeButton={false} render={<Link href="/candidate/graph" />}>
          See the effect on your graph
        </Button>
      </div>
    </div>
  )
}
